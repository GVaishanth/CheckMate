const byType = (t: number, mg: number[], eg: number[]) => ({ t, mg: Int16Array.from(mg), eg: Int16Array.from(eg) });

const tables = [
  byType(PAWN, pawnMg, pawnEg),
  byType(KNIGHT, knightMg, knightEg),
  byType(BISHOP, bishopMg, bishopEg),
  byType(ROOK, rookMg, rookEg),
  byType(QUEEN, queenMg, queenEg),
  byType(KING, kingMg, kingEg),
];

/** PST_MG[pieceType][pstIndex] */
export const PST_MG: Int16Array[] = [];
export const PST_EG: Int16Array[] = [];
for (const t of tables) {
  PST_MG[t.t] = t.mg;
  PST_EG[t.t] = t.eg;
}

/** 0x88 square → PST index (rank*8+file). */
export const pstIndexOf = (sq: number): number => ((sq >> 4) << 3) | (sq & 7);
